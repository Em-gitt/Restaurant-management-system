CREATE TABLE sales_projections (
    id bigint NOT NULL,
    order_id bigint NOT NULL,
    order_number character varying(64) NOT NULL,
    order_type character varying(50) NOT NULL,
    platform character varying(50) NOT NULL,
    order_status character varying(50) NOT NULL,
    subtotal numeric(10,2) NOT NULL DEFAULT 0.00,
    tax numeric(10,2) NOT NULL DEFAULT 0.00,
    tip numeric(10,2) NOT NULL DEFAULT 0.00,
    total numeric(10,2) NOT NULL DEFAULT 0.00,
    commission_amount numeric(10,2) NOT NULL DEFAULT 0.00,
    net_revenue numeric(10,2) NOT NULL DEFAULT 0.00,
    order_date timestamp without time zone NOT NULL,
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_sales_order_type CHECK (((order_type)::text = ANY ((ARRAY['DINE_IN'::character varying, 'DELIVERY'::character varying, 'TAKEAWAY'::character varying])::text[])))
);

ALTER TABLE sales_projections ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME sales_projections_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY sales_projections
    ADD CONSTRAINT sales_projections_pkey PRIMARY KEY (id);

ALTER TABLE ONLY sales_projections
    ADD CONSTRAINT uk_sales_projections_order_id UNIQUE (order_id);

CREATE INDEX idx_sales_projections_date ON sales_projections(order_date);
CREATE INDEX idx_sales_projections_platform ON sales_projections(platform);
CREATE INDEX idx_sales_projections_type ON sales_projections(order_type);
