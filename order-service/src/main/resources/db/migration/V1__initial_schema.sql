CREATE TABLE orders (
    id bigint NOT NULL,
    order_number character varying(64) NOT NULL,
    order_type character varying(50) NOT NULL,
    status character varying(50) NOT NULL,
    table_id bigint,
    waiter_id bigint,
    customer_name character varying(150),
    customer_phone character varying(50),
    delivery_address character varying(255),
    subtotal numeric(10,2) NOT NULL DEFAULT 0.00,
    tax numeric(10,2) NOT NULL DEFAULT 0.00,
    tip numeric(10,2) NOT NULL DEFAULT 0.00,
    total numeric(10,2) NOT NULL DEFAULT 0.00,
    notes character varying(500),
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_orders_status CHECK (((status)::text = ANY ((ARRAY['PENDING'::character varying, 'CONFIRMED'::character varying, 'IN_PREPARATION'::character varying, 'READY'::character varying, 'DELIVERED'::character varying, 'PAID'::character varying, 'CANCELLED'::character varying])::text[]))),
    CONSTRAINT chk_orders_type CHECK (((order_type)::text = ANY ((ARRAY['DINE_IN'::character varying, 'DELIVERY'::character varying, 'TAKEAWAY'::character varying])::text[])))
);

ALTER TABLE orders ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME orders_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY orders
    ADD CONSTRAINT orders_pkey PRIMARY KEY (id);

ALTER TABLE ONLY orders
    ADD CONSTRAINT uk_orders_order_number UNIQUE (order_number);

CREATE TABLE order_items (
    id bigint NOT NULL,
    order_id bigint NOT NULL,
    dish_id bigint NOT NULL,
    dish_name character varying(150) NOT NULL,
    quantity integer NOT NULL,
    unit_price numeric(10,2) NOT NULL,
    subtotal numeric(10,2) NOT NULL,
    special_instructions character varying(255),
    CONSTRAINT chk_order_items_quantity CHECK (quantity > 0)
);

ALTER TABLE order_items ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME order_items_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY order_items
    ADD CONSTRAINT order_items_pkey PRIMARY KEY (id);

ALTER TABLE ONLY order_items
    ADD CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE;
