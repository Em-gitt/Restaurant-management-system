CREATE TABLE employees (
    id bigint NOT NULL,
    user_id bigint,
    first_name character varying(100) NOT NULL,
    last_name character varying(100) NOT NULL,
    email character varying(255) NOT NULL,
    phone character varying(50),
    role character varying(50) NOT NULL,
    shift character varying(50) NOT NULL,
    active boolean NOT NULL DEFAULT true,
    hire_date date NOT NULL,
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT employees_role_check CHECK (((role)::text = ANY ((ARRAY['ADMIN'::character varying, 'WAITER'::character varying, 'CHEF'::character varying, 'CASHIER'::character varying])::text[]))),
    CONSTRAINT employees_shift_check CHECK (((shift)::text = ANY ((ARRAY['MORNING'::character varying, 'AFTERNOON'::character varying, 'NIGHT'::character varying, 'FULL_TIME'::character varying])::text[])))
);

ALTER TABLE employees ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME employees_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY employees
    ADD CONSTRAINT employees_pkey PRIMARY KEY (id);

ALTER TABLE ONLY employees
    ADD CONSTRAINT uk_employees_email UNIQUE (email);
