    ADD CONSTRAINT uk_payments_transaction_number UNIQUE (transaction_number);

ALTER TABLE ONLY payments
    ADD CONSTRAINT uk_payments_receipt_number UNIQUE (receipt_number);

CREATE INDEX idx_payments_order_id ON payments(order_id);
