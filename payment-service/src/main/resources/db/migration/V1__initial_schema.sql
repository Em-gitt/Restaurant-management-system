CREATE TABLE payments (
    id bigint NOT NULL,
    order_id bigint NOT NULL,
    transaction_number character varying(64) NOT NULL,
    payment_method character varying(50) NOT NULL,
    status character varying(50) NOT NULL,
    amount numeric(10,2) NOT NULL,
    tip numeric(10,2) NOT NULL DEFAULT 0.00,
    total_paid numeric(10,2) NOT NULL,
    cash_tendered numeric(10,2),
    change_given numeric(10,2),
    currency character varying(10) NOT NULL DEFAULT 'MXN',
    masked_card_number character varying(20),
    card_brand character varying(50),
    authorization_code character varying(50),
    receipt_number character varying(64) NOT NULL,
    notes character varying(255),
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_payment_method CHECK (((payment_method)::text = ANY ((ARRAY['CASH'::character varying, 'CREDIT_CARD'::character varying, 'DEBIT_CARD'::character varying, 'TRANSFER'::character varying, 'DELIVERY_APP'::character varying])::text[]))),
    CONSTRAINT chk_payment_status CHECK (((status)::text = ANY ((ARRAY['PENDING'::character varying, 'APPROVED'::character varying, 'REJECTED'::character varying, 'REFUNDED'::character varying])::text[])))
);

ALTER TABLE payments ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME payments_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY payments
    ADD CONSTRAINT payments_pkey PRIMARY KEY (id);

