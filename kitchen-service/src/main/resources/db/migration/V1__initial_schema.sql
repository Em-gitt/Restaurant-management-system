CREATE TABLE kitchen_orders (
    id bigint NOT NULL,
    order_id bigint NOT NULL,
    order_number character varying(64) NOT NULL,
    table_id bigint,
    order_type character varying(50) NOT NULL,
    status character varying(50) NOT NULL,
    notes character varying(500),
    started_at timestamp without time zone,
    ready_at timestamp without time zone,
    preparation_time_minutes integer,
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_kitchen_status CHECK (((status)::text = ANY ((ARRAY['PENDING'::character varying, 'PREPARING'::character varying, 'READY'::character varying, 'CANCELLED'::character varying])::text[])))
);

ALTER TABLE kitchen_orders ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME kitchen_orders_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY kitchen_orders
    ADD CONSTRAINT kitchen_orders_pkey PRIMARY KEY (id);

ALTER TABLE ONLY kitchen_orders
    ADD CONSTRAINT uk_kitchen_orders_order_id UNIQUE (order_id);

CREATE TABLE kitchen_order_items (
    id bigint NOT NULL,
    kitchen_order_id bigint NOT NULL,
    dish_id bigint NOT NULL,
    dish_name character varying(150) NOT NULL,
    quantity integer NOT NULL,
    special_instructions character varying(255),
    CONSTRAINT chk_kitchen_order_items_quantity CHECK (quantity > 0)
);

ALTER TABLE kitchen_order_items ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME kitchen_order_items_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY kitchen_order_items
    ADD CONSTRAINT kitchen_order_items_pkey PRIMARY KEY (id);

ALTER TABLE ONLY kitchen_order_items
    ADD CONSTRAINT fk_kitchen_order_items_order FOREIGN KEY (kitchen_order_id) REFERENCES kitchen_orders(id) ON DELETE CASCADE;
