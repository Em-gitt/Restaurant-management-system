CREATE TABLE ingredients (
    id bigint NOT NULL,
    name character varying(150) NOT NULL,
    unit_of_measure character varying(50) NOT NULL,
    current_stock numeric(12,3) NOT NULL DEFAULT 0.000,
    minimum_stock numeric(12,3) NOT NULL DEFAULT 0.000,
    unit_cost numeric(10,2) NOT NULL DEFAULT 0.00,
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_ingredients_current_stock CHECK (current_stock >= 0)
);

ALTER TABLE ingredients ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME ingredients_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY ingredients
    ADD CONSTRAINT ingredients_pkey PRIMARY KEY (id);

ALTER TABLE ONLY ingredients
    ADD CONSTRAINT uk_ingredients_name UNIQUE (name);

CREATE TABLE dish_recipes (
    id bigint NOT NULL,
    dish_id bigint NOT NULL,
    ingredient_id bigint NOT NULL,
    quantity_required numeric(12,3) NOT NULL,
    CONSTRAINT chk_quantity_required CHECK (quantity_required > 0)
);

ALTER TABLE dish_recipes ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME dish_recipes_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY dish_recipes
    ADD CONSTRAINT dish_recipes_pkey PRIMARY KEY (id);

ALTER TABLE ONLY dish_recipes
    ADD CONSTRAINT uk_dish_recipes_dish_ingredient UNIQUE (dish_id, ingredient_id);

ALTER TABLE ONLY dish_recipes
    ADD CONSTRAINT fk_dish_recipes_ingredient FOREIGN KEY (ingredient_id) REFERENCES ingredients(id) ON DELETE CASCADE;

CREATE TABLE inventory_movements (
    id bigint NOT NULL,
    ingredient_id bigint NOT NULL,
    movement_type character varying(50) NOT NULL,
    quantity numeric(12,3) NOT NULL,
    previous_stock numeric(12,3) NOT NULL,
    new_stock numeric(12,3) NOT NULL,
    reference_id character varying(100),
    reason character varying(255),
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_inventory_movements_type CHECK (((movement_type)::text = ANY ((ARRAY['IN'::character varying, 'OUT'::character varying, 'ADJUSTMENT'::character varying, 'ORDER_CONSUMPTION'::character varying])::text[])))
);

ALTER TABLE inventory_movements ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME inventory_movements_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY inventory_movements
    ADD CONSTRAINT inventory_movements_pkey PRIMARY KEY (id);

ALTER TABLE ONLY inventory_movements
    ADD CONSTRAINT fk_inventory_movements_ingredient FOREIGN KEY (ingredient_id) REFERENCES ingredients(id);

