CREATE TABLE delivery_orders (
    id bigint NOT NULL,
    platform character varying(50) NOT NULL,
    external_order_id character varying(100) NOT NULL,
    internal_order_id bigint,
    customer_name character varying(150) NOT NULL,
    customer_phone character varying(50),
    delivery_address character varying(255) NOT NULL,
    order_total numeric(10,2) NOT NULL,
    commission_rate numeric(5,2) NOT NULL DEFAULT 0.00,
    commission_amount numeric(10,2) NOT NULL DEFAULT 0.00,
    net_payout numeric(10,2) NOT NULL DEFAULT 0.00,
    status character varying(50) NOT NULL,
    raw_payload text,
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_delivery_platform_external_id UNIQUE (platform, external_order_id),
    CONSTRAINT chk_delivery_platform CHECK (((platform)::text = ANY ((ARRAY['RAPPI'::character varying, 'DIDI_FOOD'::character varying, 'UBER_EATS'::character varying])::text[]))),
    CONSTRAINT chk_delivery_status CHECK (((status)::text = ANY ((ARRAY['RECEIVED'::character varying, 'ORDER_CREATED'::character varying, 'IN_TRANSIT'::character varying, 'DELIVERED'::character varying, 'CANCELLED'::character varying, 'FAILED'::character varying])::text[])))
);

ALTER TABLE delivery_orders ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME delivery_orders_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY delivery_orders
    ADD CONSTRAINT delivery_orders_pkey PRIMARY KEY (id);

CREATE INDEX idx_delivery_orders_platform ON delivery_orders(platform);
CREATE INDEX idx_delivery_orders_internal_id ON delivery_orders(internal_order_id);
